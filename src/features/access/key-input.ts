/**
 * Приведение вводимого ключа к каноническому виду.
 *
 * Ключ почти всегда вставляют из мессенджера — вместе с пробелами, переводом
 * строки, длинным тире вместо дефиса и в любом регистре. Всё это чинится молча:
 * отказ «неверный формат» на человеческой опечатке выглядит как отказ в доступе.
 *
 * Вынесено из экрана отдельно, потому что это правило, а не оформление, и его
 * нужно проверять тестом.
 */

const PREFIX = "NZM";
const GROUPS = 3;
const GROUP_LENGTH = 4;

export function formatKeyInput(raw: string): string {
  const clean = raw
    .toUpperCase()
    .replace(/[–—]/g, "-")
    .replace(/[^A-Z0-9]/g, "")
    .replace(new RegExp(`^${PREFIX}`), "");

  const groups = clean.slice(0, GROUPS * GROUP_LENGTH).match(/.{1,4}/g) ?? [];
  return [PREFIX, ...groups].join("-");
}

/**
 * Ключ введён целиком. Нужно, чтобы кнопка не отправляла половину ключа: такая
 * попытка тратится и учитывается в лимите попыток наравне с настоящей.
 *
 * Проверяется только длина и форма. Допустимый алфавит — дело сервера: он
 * отвечает одинаково на «неизвестный ключ» и «отключённый», и разбирать буквы на
 * клиенте значило бы подсказывать перебирающему, какие ключи вообще бывают.
 */
export function isKeyComplete(value: string): boolean {
  return new RegExp(`^${PREFIX}(-[A-Z0-9]{${String(GROUP_LENGTH)}}){${String(GROUPS)}}$`).test(
    formatKeyInput(value),
  );
}
