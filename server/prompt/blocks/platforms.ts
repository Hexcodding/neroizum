/**
 * Правила площадок. Знание российских соцсетей — то, чего нет у зарубежных
 * аналогов и чего не даст обычная переписка с моделью.
 *
 * Главное изменение против третьей версии: соблюдение площадок стало
 * обязательным. Раньше при выборе четырёх площадок можно было получить четыре
 * одинаковых поста в стиле Telegram — в промпте не было ни требования
 * «площадка строго из списка», ни требования распределить посты поровну.
 * Теперь площадка каждого поста задана расписанием, а здесь описано, чем
 * посты для разных площадок обязаны отличаться.
 */
import { PLATFORMS, type PlatformId } from "@contracts";

const PLATFORM_RULES: Readonly<Record<PlatformId, string>> = {
  telegram:
    "личный опыт и внутрянка, прямая речь автора, уместны списки и короткие абзацы; читают внимательно и целиком, поэтому здесь допустим самый плотный по смыслу текст",
  vk:
    "упор на удержание внимания и живой диалог: сильное первое предложение, вопрос по делу в конце, повод ответить в комментариях; аудитория шире и холоднее, чем в Telegram",
  max:
    "функциональный короткий текст: суть в первых строках, конкретная польза внутри лимита, триггеры доверия и вовлекающий вопрос в конце; воды не терпит",
  tiktok:
    "текст под видео короткий, а вся работа в сценарии: 0–3 секунды крючок, 3–15 секунд тело, 15–60 секунд вывод; сценарий пиши по секундам в поле script",
  ok:
    "«ламповый» тёплый язык для аудитории 45+: без англицизмов и профессионального жаргона, с уважением и без снисходительности, полезные списки, уместна ностальгия и семейные сюжеты",
};

function platformSection(id: PlatformId): string {
  const platform = PLATFORMS[id];
  const { min, max } = platform.textLength;
  return `- ${platform.name} (идентификатор ${id}): ${PLATFORM_RULES[id]}. Длина postContent ${min}–${max} знаков. Пропорции картинки --ar ${platform.imageAspectRatio}.`;
}

export function buildPlatformsBlock(platforms: readonly PlatformId[]): string {
  const sections = platforms.map(platformSection).join("\n");

  return `ПЛОЩАДКИ И ИХ РАЗЛИЧИЯ:
${sections}

ОБЯЗАТЕЛЬНО:
- поле platform каждого поста берётся строго из расписания, менять его нельзя;
- текст поста адаптируется под свою площадку по правилам выше. Один и тот же текст, скопированный на две площадки, считается ошибкой;
- если для двух площадок тема совпадает, угол подачи, длина и призыв обязаны различаться;
- лимит длины площадки соблюдается, но за счёт плотности смысла, а не за счёт выбрасывания пользы.`;
}
