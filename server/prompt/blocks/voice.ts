/**
 * Голос и живость текста.
 *
 * Зачем отдельный блок. Запрет выдумывать факты — правило необходимое: без него
 * модель насочиняет цен, акций и исследований. Но у запрета есть цена: самый
 * безопасный для модели способ ничего не выдумать — писать общими словами. Так
 * появляются посты вида «Многие предприниматели думают… На самом деле…»: ни
 * одного проверяемого утверждения и ни одной живой строки.
 *
 * Здесь стоит противовес: требование конкретности и ритма. Живость не украшение
 * — пост без неё не дочитывают, и вся польза внутри остаётся непрочитанной.
 */

/**
 * Штамп как правило, а не как строка.
 *
 * Первая версия списка перечисляла точные фразы, и модель обошла её одним
 * синонимом: вместо запрещённого «многие предприниматели думают» написала
 * «многие предприниматели видят». Перечислять синонимы можно бесконечно и
 * всё равно не угадать, поэтому запрещается схема оборота.
 *
 * label — как штамп называется в промпте, человеку и модели. pattern — как он
 * ищется в готовом посте проверкой качества. Оба поля рядом намеренно: запрет
 * в инструкции и проверка результата не должны расходиться.
 */
export interface ClicheRule {
  readonly label: string;
  readonly pattern: RegExp;
}

export const CLICHE_RULES: readonly ClicheRule[] = [
  {
    label: "«многие думают / большинство считает / каждый из нас» — и любые обороты про то, что думает безымянное большинство",
    pattern:
      /каждый\s+из\s+нас|(?:мног\p{L}*|большинств\p{L}*)\s+(?:\p{L}+\s+){0,2}(?:дума|счита|вид|увере|полага|мечта|бо[яе])\p{L}*/iu,
  },
  {
    label: "«не волшебная палочка», «не панацея», «не серебряная пуля»",
    pattern: /волшебн\p{L}*\s+(?:палочк|таблетк)\p{L}*|серебрян\p{L}*\s+пул\p{L}*|панаце\p{L}*/iu,
  },
  {
    label: "«в современном мире», «в эпоху цифровизации», «на сегодняшний день»",
    pattern: /в\s+(?:современном\s+мире|эпоху\s+\p{L}+|наше\s+время)|на\s+сегодняшний\s+день/iu,
  },
  {
    label: "«ни для кого не секрет», «как известно», «по мнению экспертов»",
    pattern: /ни\s+для\s+кого\s+не\s+секрет|не\s+секрет,?\s+что|как\s+известно|по\s+мнению\s+экспертов/iu,
  },
  {
    label: "«давайте разберёмся», «представьте себе», «погрузитесь в мир»",
    pattern: /давайте\s+разбер|в\s+этой\s+статье|представьте\s+себе|погрузитесь\s+в\s+мир/iu,
  },
  {
    label: "«начните с малого», «подходите системно», «тестируйте гипотезы», «требует правильного подхода» — совет, который подходит любому бизнесу и потому не помогает никому",
    pattern:
      /начн\p{L}*\s+с\s+малого|подходите\s+системно|тестируйте\s+гипотез\p{L}*|требует\s+(?:правильного\s+подход|системного\s+подход|комплексного\s+подход)\p{L}*/iu,
  },
  {
    label: "«всё гениальное просто», «время — деньги» и прочие поговорки вместо мысли",
    pattern: /вс[её]\s+гениальное\s+просто|время\s*[—-]\s*деньги/iu,
  },
  {
    label: "приветствие «Друзья!» в начале и «Ставьте лайки» в конце",
    pattern: /^друзья[!,]|ставьте\s+лайк\p{L}*|подписывайтесь,?\s+чтобы\s+не\s+пропустить/iu,
  },
  {
    label: "пустые оценки «уникальный» и «инновационный» вместо конкретного свойства",
    pattern: /(?<!\p{L})уникальн\p{L}*(?!\p{L})|(?<!\p{L})инновационн\p{L}*(?!\p{L})/iu,
  },
];

/** Найденный в тексте штамп — сам фрагмент, чтобы объяснить модели предметно. */
export function findCliche(text: string): string | null {
  for (const rule of CLICHE_RULES) {
    const found = rule.pattern.exec(text);
    if (found !== null) return found[0].trim();
  }
  return null;
}

function clicheLines(): string {
  return CLICHE_RULES.map((rule) => `- ${rule.label};`).join("\n");
}

