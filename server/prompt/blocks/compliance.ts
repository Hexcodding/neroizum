/**
 * Юридический режим «инфо-план»: контент как информирование о деятельности,
 * без рекламных формулировок.
 *
 * Редкая фича — у конкурентов почти не встречается, и для части клиентов она
 * решающая. Блок включается только по выбору пользователя: в обычном режиме
 * ограничивать продающие посты нельзя, иначе продукт перестанет продавать.
 *
 * Юридическая оговорка: блок помогает избежать рекламных формулировок, но не
 * является юридическим заключением. Формулировку дисклеймера для интерфейса
 * нужно согласовать с заказчиком до запуска на живых клиентов.
 */

/** Слова, по которым публикацию проще всего опознать как рекламную. */
const FORBIDDEN_WORDS = [
  "акция",
  "скидка",
  "распродажа",
  "промокод",
  "купи",
  "закажи",
  "успей",
  "только сегодня",
  "спецпредложение",
  "выгодная цена",
] as const;

export const INFO_PLAN_BLOCK = `РЕЖИМ ИНФО-ПЛАНА ВКЛЮЧЁН. Весь контент — информирование о деятельности, а не реклама.

ЗАПРЕЩЕНЫ слова и конструкции: ${FORBIDDEN_WORDS.join(", ")}. Запрещены призывы купить, заказать и поторопиться, а также любые упоминания цен, условий покупки и ограниченных по времени предложений.

ДОПУСТИМО: разбор случаев из практики, обзоры, экспертное мнение, объяснение процессов, полезные советы, наблюдения, ответы на вопросы, результаты работы без призыва её заказать.

В поле type допустимы только значения «Обучающий» и «Экспертный». В поле cta вместо призыва к покупке ставь нейтральное продолжение разговора: предложение задать вопрос, рассказать свой опыт или сохранить пост.`;

export function buildComplianceBlock(infoPlanMode: boolean): string {
  return infoPlanMode ? INFO_PLAN_BLOCK : "";
}

export const INFO_PLAN_FORBIDDEN_WORDS: readonly string[] = FORBIDDEN_WORDS;
