/** Сколько раз подряд допустима одна и та же рубрика. */
export const MAX_RUBRIC_REPEATS_IN_ROW = 1;

/** Сколько своих рубрик модель может добавить под нишу. */
const MAX_CUSTOM_RUBRICS = 2;

function rubricLine(rubric: Rubric): string {
  return `- «${rubric.name}» — ${rubric.description}. Подходит для типов: ${rubric.types.join(", ")}.`;
}

export function buildRubricsBlock(): string {
  return `КАТАЛОГ РУБРИК. Рубрика — это узнаваемая постоянная форма постов: читатель привыкает к ней и ждёт следующий выпуск. В поле rubric пиши название рубрики точно так, как оно указано здесь, без кавычек.

${RUBRICS.map(rubricLine).join("\n")}

Правила работы с рубриками:
- рубрика обязана соответствовать типу поста: «Возражение» не может быть Обучающим постом;
- одна и та же рубрика не может стоять более ${MAX_RUBRIC_REPEATS_IN_ROW} раза подряд;
- в плане должно быть использовано не менее пяти разных рубрик;
- если каталог не покрывает специфику бизнеса, можно добавить не более ${MAX_CUSTOM_RUBRICS} своих рубрик: короткое название из одного-двух слов, по тому же принципу — повторяемая форма, а не разовая тема.`;
}
