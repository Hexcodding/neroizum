/**
 * Блок исправления. Используется, когда проверка качества нашла проблемные
 * посты и мы просим модель переделать именно их.
 *
 * Смысл в том, чтобы не просить «сделай лучше», а назвать конкретную причину:
 * обещал пять пунктов — перечисли пять. Причины формулирует проверка качества,
 * здесь они только оформляются.
 */

export function buildRepairBlock(reasons: readonly string[]): string {
  if (reasons.length === 0) return "";

  return `ИСПРАВЛЕНИЕ. Предыдущая версия этих постов не прошла проверку. Что было не так:
${reasons.map((reason) => `- ${reason}`).join("\n")}

Сделай эти посты заново с нуля, устранив перечисленное. Темы можно менять, если так получится честнее раскрыть пользу. Все остальные правила задания остаются в силе.`;
}
