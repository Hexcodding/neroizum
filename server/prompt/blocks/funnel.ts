/**
 * Точное количество постов каждого типа. Считается методом наибольших
 * остатков, чтобы сумма совпала с общим количеством постов и модели не
 * приходилось округлять проценты самостоятельно.
 */
export function expectedTypeCounts(total: number, mix: ContentMix): Record<ContentType, number> {
  const parts = CONTENT_TYPES.map((type) => {
    const exact = (total * mix[type]) / 100;
    const floor = Math.floor(exact);
    return { type, count: floor, remainder: exact - floor };
  });

  let assigned = parts.reduce((sum, part) => sum + part.count, 0);
  const byRemainder = [...parts].sort((left, right) => right.remainder - left.remainder);

  let index = 0;
  while (assigned < total && byRemainder.length > 0) {
    const part = byRemainder[index % byRemainder.length];
    if (part !== undefined) {
      part.count += 1;
      assigned += 1;
    }
    index += 1;
  }

  const result: Record<ContentType, number> = {
    Обучающий: 0,
    Вовлекающий: 0,
    Экспертный: 0,
    Продающий: 0,
  };
  for (const part of parts) {
    result[part.type] = part.count;
  }
  return result;
}

function countsLine(counts: Record<ContentType, number>): string {
  return CONTENT_TYPES.map((type) => `${type} — ${String(counts[type])}`).join(", ");
}

export function buildFunnelBlock(goal: GoalId, stage: ChannelStageId, totalPosts: number): string {
  const counts = expectedTypeCounts(totalPosts, CONTENT_MIX_BY_GOAL[goal]);

  return `СТРАТЕГИЯ ПОД ЦЕЛЬ.
${GOAL_STRATEGY[goal]}

СТАДИЯ ПРОЕКТА. ${STAGE_NOTES[stage]}

ТОЧНЫЕ ПРОПОРЦИИ ТИПОВ на ${totalPosts} постов: ${countsLine(counts)}.
Соблюдай это распределение точно: количество постов каждого типа должно совпасть с указанным. Тип возвращай в поле type строго одним из значений: ${CONTENT_TYPES.join(", ")}.`;
}
