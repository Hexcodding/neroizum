/**
 * Запрещённые конструкции заданы данными, а не абзацем внутри промпта: по этому
 * же списку проверка качества ищет тизеры в готовых постах. Иначе запрет в
 * инструкции и проверка результата рано или поздно разойдутся.
 */
export const TEASER_PHRASES: readonly string[] = [
  "смотри карусель",
  "смотрите карусель",
  "листай дальше",
  "листайте дальше",
  "подробности в карусели",
  "в этом посте расскажу",
  "сейчас объясню",
  "читай до конца",
  "читайте до конца",
  "ссылка в профиле",
  "ссылка в описании",
  "продолжение завтра",
  "во второй части",
  "подробнее в следующем посте",
  "пиши в личку — расскажу",
];

function teaserLines(): string {
  return TEASER_PHRASES.map((phrase) => `- «${phrase}»;`).join("\n");
}

