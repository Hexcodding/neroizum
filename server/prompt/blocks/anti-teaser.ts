/**
 * Zero Click Value — главный блок промпта.
 *
 * Он один отделяет продукт от генератора воды. Без него модель охотно пишет
 * «разберём 5 ошибок» и не перечисляет ни одной: формально пост есть,
 * публиковать нечего.
 *
 * Здесь только про пользу внутри поста. Требования к голосу и живости живут
 * в blocks/voice.ts: это отдельная задача, и смешивать их в одном блоке значит
 * править оба, меняя одно.
 *
 * Самопроверка перед выдачей вынесена в служебное поле _zeroClickCheck схемы
 * ответа: «ответь себе молча» модель пропускала, а обязательное поле в JSON
 * она заполнить обязана.
 *
 * Менять этот текст можно только осознанно и с повышением версии промпта.
 */

/**
 * Запрещённые конструкции заданы данными, а не абзацем внутри промпта: по этому
 * же списку проверка качества ищет тизеры в готовых постах. Иначе запрет в
 * инструкции и проверка результата рано или поздно разойдутся.
 */
export const TEASER_PHRASES: readonly string[] = [
  "смотри карусель",
  "смотрите карусель",
  "листай дальше",
  "листайте дальше",
  "подробности в карусели",
  "в этом посте расскажу",
  "давайте разберёмся",
  "давайте разберемся",
  "сейчас объясню",
  "читай до конца",
  "читайте до конца",
  "ссылка в профиле",
  "ссылка в описании",
  "продолжение завтра",
  "во второй части",
  "подробнее в следующем посте",
  "пиши в личку — расскажу",
];

function teaserLines(): string {
  return TEASER_PHRASES.map((phrase) => `- «${phrase}»;`).join("\n");
}

