/**
 * Версия промпта. Записывается в каждый сгенерированный план, чтобы через
 * месяц можно было понять, каким промптом сделан конкретный результат:
 * без этого невозможно сравнивать качество после правок инструкций.
 *
 * Формат: МАЖОРНАЯ.МИНОРНАЯ.ПРАВКА
 * Мажорная меняется при смене контракта ответа модели, минорная — при
 * изменении смысла блоков, правка — при уточнении формулировок.
 */

/**
 * История версий:
 * 1.0.0 — первая собранная версия v2: Zero Click Value и профиль бренда
 *         перенесены из третьей версии, визуальная матрица из десяти стилей
 *         возвращена из прототипа, добавлены стратегия под цель, каталог
 *         рубрик, обязательное соблюдение площадок и расписание, посчитанное
 *         кодом вместо модели.
 * 1.1.0 — блок о голосе и живости: требование конкретного начала, неровного
 *         ритма и прямой речи как противовес запрету выдумывать факты. Список
 *         штампов вынесен в данные и проверяется программой. Эмодзи стали
 *         требованием, а не разрешением с оговорками: прежняя формулировка
 *         «умеренно и только там, где уместны» читалась моделью как «лучше
 *         никаких», и посты выходили без единого.
 * 2.0.0 — контракт ответа модели: служебное поле _zeroClickCheck стоит первым
 *         в схеме, чтобы модель ответила на три вопроса Zero Click Value до
 *         текста. В сохранённый пост поле не попадает. Данные клиента собраны
 *         в один тег <CLIENT_DATA>. Переписаны роль, антитизер, голос; на
 *         визуале кириллица по умолчанию, латиница — только если так в данных
 *         клиента. Стоп-слова «уникальный» и «инновационный» проверяются
 *         программой.
 */
export const PROMPT_VERSION = "2.0.0";

const VERSION_PATTERN = /^\d+\.\d+\.\d+$/;

export function isValidPromptVersion(value: string): boolean {
  return VERSION_PATTERN.test(value);
}
